export const BENGALI_NUMERALS: { [key: string]: string } = {
  '0': '০',
  '1': '১',
  '2': '২',
  '3': '৩',
  '4': '৪',
  '5': '৫',
  '6': '৬',
  '7': '৭',
  '8': '৮',
  '9': '৯',
};

export const toBengaliNumerals = (val: string | number): string => {
  const str = String(val);
  return str.replace(/[0-9]/g, (digit) => BENGALI_NUMERALS[digit] || digit);
};

export const CURRENCY_SYMBOLS: Record<Currency, { symbol: string; nameEn: string; nameBn: string }> = {
  BDT: { symbol: '৳', nameEn: 'BDT (Taka)', nameBn: 'টাকা (৳)' },
  USD: { symbol: '$', nameEn: 'USD ($)', nameBn: 'ইউএস ডলার ($)' },
  EUR: { symbol: '€', nameEn: 'EUR (€)', nameBn: 'ইউরো (€)' },
  INR: { symbol: '₹', nameEn: 'INR (₹)', nameBn: 'রুপি (₹)' },
  GBP: { symbol: '£', nameEn: 'GBP (£)', nameBn: 'পাউন্ড (£)' },
};

export const formatCurrency = (amount: number, currency: Currency = 'BDT', lang: Language = 'en'): string => {
  const sym = CURRENCY_SYMBOLS[currency]?.symbol || '৳';
  const formattedNumber = new Intl.NumberFormat('en-IN', {
    maximumFractionDigits: 0,
  }).format(Math.abs(amount));

  if (lang === 'bn') {
    return `${sym} ${toBengaliNumerals(formattedNumber)}`;
  }
  return `${sym} ${formattedNumber}`;
};

export const formatPlainNumber = (val: number | string, lang: Language = 'en'): string => {
  if (lang === 'bn') {
    return toBengaliNumerals(val);
  }
  return String(val);
};

